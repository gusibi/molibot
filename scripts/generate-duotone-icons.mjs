#!/usr/bin/env node
/**
 * Generate the Duotone icon module for the desktop app from the official
 * Reicon icon data (@iconify-json/reicon, synced from reicon.dev).
 *
 * Usage: node scripts/generate-duotone-icons.mjs
 *
 * The manifest below is the single place where a duotone icon is adopted:
 * - EXACT names resolve to `<kebab(name)>-duotone`.
 * - SUBSTITUTIONS map a name to an official same-concept duotone glyph when no
 *   exact variant exists (DESIGN.md "Foundations" — reviewed, explicit entries).
 * A name whose duotone body is missing from the data fails the script instead
 * of silently rendering nothing. Never hand-edit the generated modules.
 *
 * Outputs:
 * - apps/desktop/src/lib/icons/duotone/bodies.generated.ts  (body data)
 * - apps/desktop/src/lib/icons/duotone/components/<Name>.svelte
 *   (one component per adopted name, sharing the Reicon component props
 *   contract so they drop in wherever a ReiconComponent is expected)
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DATA_FILE = join(ROOT, "node_modules", "@iconify-json", "reicon", "icons.json");
const OUT_DIR = join(ROOT, "apps", "desktop", "src", "lib", "icons", "duotone");
const OUT_FILE = join(OUT_DIR, "bodies.generated.ts");
const COMPONENTS_DIR = join(OUT_DIR, "components");

/** Reicon export names with an exact `<kebab>-duotone` counterpart. */
const EXACT = [
  "ArrowDown",
  "ArrowRight",
  "Bell",
  "Box",
  "BranchUp",
  "ChatDots",
  "CheckCircle",
  "CircleArrowsDown",
  "Clapperboard",
  "Cloud",
  "CloudCross",
  "Code",
  "CodeFile",
  "Compass",
  "Copy",
  "Cpu",
  "Download",
  "Eye",
  "EyeClosed",
  "FileText",
  "Folder",
  "FolderOpen",
  "Gallery",
  "Handshake",
  "History",
  "Inbox",
  "InfoCircle",
  "Layers",
  "Lightning",
  "List",
  "Magnifier",
  "Map",
  "Microphone",
  "Notebook",
  "Palette",
  "Paperclip",
  "Pen",
  "Plane2",
  "PlugCircle",
  "Pulse",
  "Ranking",
  "Reorder2",
  "ShieldAlert",
  "Sidebar",
  "Socket",
  "Soundwave",
  "Speaker",
  "SquareArrowUp",
  "Star",
  "Stop",
  "Stopwatch",
  "Trash",
  "TuningSquare2",
  "User",
  "Vacuum2",
  "Wand",
];
/** Names rendered with an official same-concept duotone glyph. */
const SUBSTITUTIONS = {
  CalendarDays: "calendar-duotone",
  ChartLine: "chart-duotone",
  Crosshairs: "target-duotone",
  EyeSlash: "eye-closed-duotone",
  Files: "docs-duotone",
  Grid: "squares-duotone",
  MagicWand: "wand3-duotone",
  More: "more-h-duotone",
  PenLine: "pen2-duotone",
  Search: "search2-duotone",
  ShieldSlash: "shield-cross-duotone",
  ThumbsUp: "like-duotone",
  Timer: "stopwatch-duotone",
  TriangleWarning: "alert-triangle-duotone",
  Video: "camera-record-duotone",
};

const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

const data = JSON.parse(readFileSync(DATA_FILE, "utf8"));
const bodies = {};
for (const name of EXACT) {
  bodies[name] = data.icons[`${kebab(name)}-duotone`]?.body;
}
for (const [name, duotone] of Object.entries(SUBSTITUTIONS)) {
  bodies[name] = data.icons[duotone]?.body;
}

const missing = Object.entries(bodies)
  .filter(([, body]) => !body)
  .map(([name]) => name);
if (missing.length > 0) {
  console.error(`generate-duotone-icons: missing duotone bodies for: ${missing.join(", ")}`);
  process.exit(1);
}

const sorted = Object.fromEntries(Object.entries(bodies).sort(([a], [b]) => a.localeCompare(b)));
const generated = `/**
 * Generated by scripts/generate-duotone-icons.mjs from @iconify-json/reicon.
 * Do not edit; extend the script manifest and regenerate instead.
 */
export const DUOTONE_ICON_BODIES = {
${Object.entries(sorted)
  .map(([name, body]) => `  ${name}: ${JSON.stringify(body)},`)
  .join("\n")}
} as const;

export type DuotoneIconName = keyof typeof DUOTONE_ICON_BODIES;
`;

writeFileSync(OUT_FILE, generated);

const COMPONENT_TEMPLATE = (name) => `<script lang="ts">
  import { DUOTONE_ICON_BODIES } from "../bodies.generated";

  export let size: string | number = 24;
  export let color: string | undefined = undefined;
  // Duotone is a single weight; the prop stays accepted (and unused) so these
  // components drop in wherever reicon-svelte components are expected.
  // svelte-ignore export_let_unused
  export let weight: "Outline" | "Filled" = "Outline";
  // svelte-ignore export_let_unused
  export let strokeWidth: string | number | undefined = undefined;

  let className = "";
  export { className as class };

  let customStyle = "";
  export { customStyle as style };

  const body = DUOTONE_ICON_BODIES["${name}"];
</script>

<!--
  Generated by scripts/generate-duotone-icons.mjs — do not edit.
  ${name} (Reicon duotone weight), props contract matches reicon-svelte components.
-->
<svg
  xmlns="http://www.w3.org/2000/svg"
  width={size}
  height={size}
  viewBox="0 0 24 24"
  fill="none"
  class="reicon duotone {className}"
  style={color != null ? \`color: \${color}; \${customStyle}\` : customStyle}
  aria-hidden="true"
  focusable="false"
  {...$$restProps}
>
  {@html body}
</svg>
`;

if (existsSync(COMPONENTS_DIR)) {
  for (const entry of readdirSync(COMPONENTS_DIR)) {
    rmSync(join(COMPONENTS_DIR, entry));
  }
} else {
  mkdirSync(COMPONENTS_DIR, { recursive: true });
}
for (const name of Object.keys(sorted)) {
  writeFileSync(join(COMPONENTS_DIR, `${name}.svelte`), COMPONENT_TEMPLATE(name));
}

console.log(
  `generate-duotone-icons: wrote ${Object.keys(sorted).length} bodies to ${OUT_FILE} and ${Object.keys(sorted).length} components to ${COMPONENTS_DIR}`,
);
