#!/usr/bin/env node
/**
 * Generate the Duotone icon body module for the desktop app from the official
 * Reicon icon data (@iconify-json/reicon, synced from reicon.dev).
 *
 * Usage: node scripts/generate-duotone-icons.mjs
 *
 * The manifest below is the single place where a duotone icon is adopted:
 * - EXACT names resolve to `<kebab(name)>-duotone`.
 * - SUBSTITUTIONS map a name to an official same-concept duotone glyph when no
 *   exact variant exists (DESIGN.md "Foundations" — reviewed, explicit entries).
 * A name whose duotone body is missing from the data fails the script instead
 * of silently rendering nothing. Never hand-edit the generated module.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DATA_FILE = join(ROOT, "node_modules", "@iconify-json", "reicon", "icons.json");
const OUT_FILE = join(ROOT, "apps", "desktop", "src", "lib", "icons", "duotone", "bodies.generated.ts");

/** Reicon export names with an exact `<kebab>-duotone` counterpart. */
const EXACT = [
  "Bell",
  "Box",
  "BranchUp",
  "ChatDots",
  "CheckCircle",
  "Clapperboard",
  "Cloud",
  "CloudCross",
  "CodeFile",
  "Cpu",
  "Eye",
  "EyeClosed",
  "FileText",
  "Folder",
  "Gallery",
  "History",
  "Inbox",
  "Magnifier",
  "Paperclip",
  "PlugCircle",
  "Pulse",
  "Ranking",
  "ShieldAlert",
  "Socket",
  "Speaker",
  "Stopwatch",
  "User",
  "Wand",
];
/** Names rendered with an official same-concept duotone glyph. */
const SUBSTITUTIONS = {
  ChartLine: "chart-duotone",
  Search: "search2-duotone",
  ShieldSlash: "shield-cross-duotone",
  TriangleWarning: "alert-triangle-duotone",
};

const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

const data = JSON.parse(readFileSync(DATA_FILE, "utf8"));
const bodies = {};
for (const name of EXACT) {
  bodies[name] = data.icons[`${kebab(name)}-duotone`]?.body;
}
for (const [name, duotone] of Object.entries(SUBSTITUTIONS)) {
  bodies[name] = data.icons[duotone]?.body;
}

const missing = Object.entries(bodies)
  .filter(([, body]) => !body)
  .map(([name]) => name);
if (missing.length > 0) {
  console.error(`generate-duotone-icons: missing duotone bodies for: ${missing.join(", ")}`);
  process.exit(1);
}

const sorted = Object.fromEntries(Object.entries(bodies).sort(([a], [b]) => a.localeCompare(b)));
const generated = `/**
 * Generated by scripts/generate-duotone-icons.mjs from @iconify-json/reicon.
 * Do not edit; extend the script manifest and regenerate instead.
 */
export const DUOTONE_ICON_BODIES = {
${Object.entries(sorted)
  .map(([name, body]) => `  ${name}: ${JSON.stringify(body)},`)
  .join("\n")}
} as const;

export type DuotoneIconName = keyof typeof DUOTONE_ICON_BODIES;
`;

writeFileSync(OUT_FILE, generated);
console.log(`generate-duotone-icons: wrote ${Object.keys(sorted).length} bodies to ${OUT_FILE}`);
