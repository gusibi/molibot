import { execFileSync } from "node:child_process";
import { resolve } from "node:path";
import { test, expect } from "./support/fixtures";
import { openChat, openSettings } from "./support/actions";
import { buildIsolatedEnv } from "./support/instance";

test("uncollected memory has its own tab, filters, failure recovery and themes @memory-uncollected", async ({page, instance}, testInfo) => {
  execFileSync(process.execPath, ["--import", "./scripts/register-loader.js", "--import", "tsx", "--input-type=module", "-e", `
    import {resolve} from 'node:path';
    import {appendMemoryGovernanceRejection} from './src/lib/server/memory/governanceLog.ts';
    const filePath=resolve(process.env.DATA_DIR,'memory-governance','rejections.jsonl');
    appendMemoryGovernanceRejection({filePath,scope:{channel:'web',externalUserId:'test-user'},action:'add',input:{content:'Please check the build now'},reason:'Transient task, not a durable fact.'});
    appendMemoryGovernanceRejection({filePath,scope:{channel:'telegram',externalUserId:'test-chat'},action:'update',input:{content:'A proposed update without enough evidence'},reason:'Insufficient evidence.'});
  `], {cwd:resolve('.'),env:buildIsolatedEnv({home:instance.home,dataDir:instance.dataDir,port:instance.port,modelUrl:instance.model.url,forbiddenDir:resolve(instance.home,'forbidden')}),stdio:'pipe'});
  await openChat(page);
  await openSettings(page);
  await page.getByRole('button',{name:'Memory',exact:true}).click();
  await page.getByRole('button',{name:'Advanced',exact:true}).click();
  const advanced=page.getByRole('dialog',{name:'Advanced',exact:true});
  await expect(advanced.getByText('Please check the build now',{exact:true})).toHaveCount(0);
  await expect(advanced.getByText('Uncollected',{exact:true})).toHaveCount(0);
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Uncollected',exact:true}).click();
  const panel=page.getByRole('region',{name:'Uncollected',exact:true});
  await expect(panel.getByRole('article')).toHaveCount(2);
  await expect(panel.getByText('Please check the build now',{exact:true})).toBeVisible();
  await expect(panel.getByText('Transient task, not a durable fact.',{exact:false})).toBeVisible();
  await expect(panel.getByText('web · test-user',{exact:true})).toBeVisible();
  await expect(panel.getByText('Update declined',{exact:true})).toBeVisible();
  const response=await page.request.get(instance.endpoint+'/api/desktop/memory?view=rejections');
  const records=(await response.json()).items;
  expect(records).toHaveLength(2);
  expect(records.every((item:any)=>item.createdAt && item.reason && item.content)).toBe(true);
  const search=panel.getByRole('textbox',{name:'Filter reason, content, or scope',exact:true});
  await search.fill('Transient');
  await expect(panel.getByRole('article')).toHaveCount(1);
  await expect(panel.getByText('1 / 2',{exact:true})).toBeVisible();
  await search.fill('test-chat');
  await expect(panel.getByText('Update declined',{exact:true})).toBeVisible();
  await search.fill('not-in-any-entry');
  await expect(panel.getByText('No matching entries. Try another keyword.',{exact:true})).toBeVisible();
  await search.fill('');
  await page.screenshot({path:testInfo.outputPath('uncollected-light.png')});
  await page.route('**/api/desktop/memory?view=rejections',route=>route.fulfill({status:503,json:{error:'test outage'}}));
  await panel.getByRole('button',{name:'Refresh',exact:true}).click();
  await expect(panel.getByRole('alert')).toHaveText('Could not load uncollected entries. Please retry.');
  await page.unroute('**/api/desktop/memory?view=rejections');
  await panel.getByRole('button',{name:'Refresh',exact:true}).click();
  await expect(panel.getByRole('article')).toHaveCount(2);
  await page.evaluate(()=>{
    window.dispatchEvent(new StorageEvent('storage',{key:'molibot-desktop-locale',newValue:'zh-CN'}));
    window.dispatchEvent(new StorageEvent('storage',{key:'molibot-desktop-appearance',newValue:'dark'}));
  });
  await page.setViewportSize({width:390,height:844});
  const zhPanel=page.getByRole('region',{name:'未收录',exact:true});
  await expect(zhPanel.getByText('未收录原因',{exact:true})).toHaveCount(2);
  await expect(zhPanel.getByText('更新未通过',{exact:true})).toBeVisible();
  expect(await zhPanel.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
  await page.screenshot({path:testInfo.outputPath('uncollected-dark-mobile.png')});
  await page.getByRole('button',{name:'全部记忆',exact:true}).click();
  await page.getByRole('button',{name:'未收录',exact:true}).click();
  await expect(zhPanel.getByRole('article')).toHaveCount(2);
  await instance.restartService();
  await zhPanel.getByRole('button',{name:'刷新',exact:true}).click();
  await expect(zhPanel.getByRole('article')).toHaveCount(2);
  await page.route('**/api/desktop/memory?view=rejections',route=>route.fulfill({json:{ok:true,items:[],counts:{total:0,add:0,update:0}}}));
  await zhPanel.getByRole('button',{name:'刷新',exact:true}).click();
  await expect(zhPanel.getByText('暂无未收录记录。',{exact:true})).toBeVisible();
});
