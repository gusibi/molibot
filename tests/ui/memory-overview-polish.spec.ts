import { test, expect } from './support/fixtures';
import { openChat, openSettings } from './support/actions';

const summary = 'Prefers concise answers with the conclusion first. Uses a local assistant to plan projects, collect reading notes and review progress. Values clear information hierarchy, visible sources and control over saved memories. '.repeat(8) + 'Full profile ends here.';
const items = Array.from({ length: 6 }, (_, i) => ({ id: `memory-${i}`, channel: 'web', externalUserId: 'test-owner', content: ['Prefers short answers and clear next steps.', 'Keeps reading notes with links to the original sources.', 'Reviews project progress each Friday.', 'Uses Svelte for the desktop interface.', 'Prefers a quiet workspace.', 'Plans the coming week on Sunday.'][i], tags: [], layer: 'long_term', domain: 'owner', type: 'user_preference', subject: `preference-${i}`, hasEmbedding: true, allowInjection: true, createdAt: '2026-10-28T12:00:00Z', updatedAt: '2026-10-30T12:00:00Z' }));
const candidates = Array.from({ length: 4 }, (_, i) => ({ id: `candidate-${i}`, status: 'pending', namespace: 'owner:test-owner', domain: i === 3 ? 'agent_self' : 'owner', type: 'user_fact', subject: `candidate-${i}`, value: ['A proposed reading preference needs your confirmation.', 'A proposed planning habit needs your confirmation.', 'A proposed workspace preference needs your confirmation.', 'A reusable technical lesson for the assistant.'][i], sources: [], confidence: 0.8, reason: 'Repeated evidence', createdAt: '2026-10-30T12:00:00Z', updatedAt: '2026-10-30T12:00:00Z' }));

test('memory overview limits the profile and prioritizes review without empty panels @memory-polish', async ({ page, instance }, info) => {
  for (const path of ['handover', 'handover/ack']) info.annotations.push({ type: 'expected-page-error', description: `/molibot-api/api/desktop/${path} due to access control checks` });
  let pending = [...candidates];
  let empty = false;
  let profileUnavailable = false;
  const sectionMeta = { scannedCount: 6, selectedCount: 6, excludedCount: 0, truncated: false, rule: 'test fixture' };
  await page.route('**/api/desktop/memory', async route => {
    if (route.request().method() === 'GET') return route.fulfill({ json: { ok: true, summary: { enabled: true, configEnabled: true, backend: 'mory', embedding: null, capabilities: {} } } });
    const action = route.request().postDataJSON().action;
    if (action === 'list-candidates') return route.fulfill({ json: { ok: true, candidates: empty ? [] : pending } });
    if (action === 'profile' && profileUnavailable) return route.fulfill({ json: { ok: true } });
    if (action === 'profile') return route.fulfill({ json: { ok: true, profile: { summary: empty ? '' : summary, currentFocus: [], attentionItems: [], stablePreferences: empty ? [] : items, recentItems: empty ? [] : items, profileFacts: [], meta: { stablePreferences: sectionMeta } } } });
    if (action === 'ignore-candidate') pending = pending.filter(item => item.id !== route.request().postDataJSON().id);
    return route.fulfill({ json: { ok: true, items: empty ? [] : items, versions: [] } });
  });
  await openChat(page);
  await openSettings(page);
  await page.getByRole('navigation', { name: 'Settings', exact: true }).getByRole('button', { name: 'Memory', exact: true }).click();
  const overview = page.locator('[data-memory-view="overview"]');
  const expand = overview.getByRole('button', { name: 'Read full profile', exact: true });
  await expect(expand).toBeVisible();
  expect((await page.locator('#memory-profile-text').innerText()).length).toBeLessThanOrEqual(180);
  await expect(overview.getByRole('heading', { name: 'Current focus', exact: true })).toHaveCount(0);
  await expect(overview.locator('.memory-recent-list li')).toHaveCount(3);
  await expect(overview.getByRole('heading', { name: 'Recently added', exact: true })).toBeInViewport();
  await page.screenshot({ path: info.outputPath('memory-overview-light.png') });
  await expand.focus();
  await page.keyboard.press('Enter');
  await expect(page.locator('#memory-profile-text')).toHaveText(summary);
  await expect(overview.locator('.memory-profile-meta')).toContainText('6 scanned');
  await overview.getByRole('button', { name: 'Collapse profile', exact: true }).click();
  const queue = overview.locator('.memory-pending-panel');
  await expect(queue).not.toHaveAttribute('open', '');
  await queue.locator('summary').focus();
  await page.keyboard.press('Enter');
  await expect(queue.locator('.memory-candidate-copy')).toHaveCount(3);
  await queue.getByRole('button', { name: "Don't save", exact: true }).first().click();
  await expect(queue.locator('.memory-candidate-copy')).toHaveCount(2);
  await queue.locator('summary').click();
  await overview.getByRole('button', { name: items[0].content, exact: true }).last().click();
  await expect(page.getByRole('dialog', { name: 'Memory', exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await page.getByRole('navigation', { name: 'Memory views' }).getByRole('button', { name: 'Topics', exact: true }).click();
  await expect(page.locator('[data-memory-view="topics"]')).toBeVisible();
  await page.getByRole('button', { name: 'All memories', exact: true }).click();
  await expect(page.locator('.memory-record')).toHaveCount(6);
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await page.evaluate(() => {
    window.dispatchEvent(new StorageEvent('storage', { key: 'molibot-desktop-locale', newValue: 'zh-CN' }));
    window.dispatchEvent(new StorageEvent('storage', { key: 'molibot-desktop-appearance', newValue: 'dark' }));
  });
  await page.setViewportSize({ width: 860, height: 700 });
  await expect(overview.getByRole('button', { name: '查看完整画像', exact: true })).toBeVisible();
  expect(await page.locator('.memory-center-shell').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('memory-overview-dark-zh.png') });
  await instance.restartService();
  empty = true;
  await page.addInitScript(() => { localStorage.setItem("molibot-desktop-locale", "zh-CN"); localStorage.setItem("molibot-desktop-appearance", "dark"); });
  await page.reload();
  await page.getByRole('button', { name: 'Molibot · 在线', exact: true }).click();
  await page.getByRole('navigation', { name: '设置', exact: true }).getByRole('button', { name: '记忆', exact: true }).click();
  await expect(overview.getByText('随着你与 Molibot 的交流增加，这里会逐渐形成一份可以检查和修正的理解。', { exact: true })).toBeVisible();
  await expect(overview.locator('.memory-overview-panel')).toHaveCount(0);
  empty = false;
  profileUnavailable = true;
  await page.evaluate(() => window.dispatchEvent(new Event('molibot:settings-changed')));
  await overview.getByRole('button', { name: '查看完整画像', exact: true }).click();
  await expect(overview.locator('.memory-profile-meta')).toHaveText('根据当前已加载的 6 条长期记忆整理。');
  await expect(overview.locator('.memory-recent-list li')).toHaveCount(3);
});
